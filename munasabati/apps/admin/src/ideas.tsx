function Calc({ kind }: { kind: "venue" | "vendor" }) {
  const v = kind === "venue";
  const [price, setPrice] = useState(v ? 12000 : 4000);
  const [extra, setExtra] = useState(v ? 3 : 4);
  const gross = price * extra;
  const after = Math.round(gross * 0.9);
  const field = (id: string, label: string, val: number, set: (n: number) => void, min: number, max: number, step: number, suffix: string) => (
    <div className="calc-f"><label htmlFor={id}>{label}</label>
      <div className="calc-in"><input id={id} type="range" min={min} max={max} step={step} value={val} onChange={(e) => set(+e.target.value)} /><b className="num">{fmt(val)} {suffix}</b></div>
    </div>
  );
  return (
    <section className="calc">
      <div className="calc-h"><Icon name="TrendingUp" size={18} /><h3>حاسبة الدخل: حط أرقامه هو قدامه</h3></div>
      <div className="calc-body">
        <div className="calc-inputs">
          {field("cp", v ? "سعر الليلة في قاعته" : "متوسط سعر الطلب عنده", price, setPrice, v ? 3000 : 500, v ? 60000 : 30000, v ? 500 : 250, "ر.س")}
          {field("cn", v ? "كم ليلة فاضية نعبيها له بالشهر" : "كم طلب إضافي نجيبه له بالشهر", extra, setExtra, 1, v ? 12 : 20, 1, v ? "ليلة" : "طلب")}
        </div>
        <div className="calc-out">
          <div className="calc-big"><small>أول ٤ شهور (صفر من سعره)</small><b className="num">{fmt(gross)}</b><em>ر.س دخل إضافي بالشهر</em></div>
          <div className="calc-row"><span>بعد ٤ شهور (١٠٪ من سعره)</span><b className="num">{fmt(after)} ر.س بالشهر</b></div>
          <div className="calc-row"><span>بالسنة تقريباً</span><b className="num">{fmt(gross * 4 + after * 8)} ر.س</b></div>
        </div>
      </div>
      <p className="calc-note">مثال توضيحي بأرقامه هو، مو وعد بعدد حجوزات. الحجوزات الفعلية تعتمد على الطلب وسرعة رده وأسعاره.</p>
    </section>
  );
}

