function Card({ i }: { i: Idea }) {
  const toast = useToast();
  const [open, setOpen] = useState(false);
  const copy = async () => { try { await navigator.clipboard.writeText(i.pitch); toast("انسخت رسالة العرض"); } catch { toast("ما قدرت أنسخ"); } };
  return (
    <article className="idea-card">
      <div className="ic-top"><span className="ic-ic"><Icon name={i.icon} size={20} /></span><span className={"pill " + ST[i.status].cls}>{ST[i.status].label}</span></div>
      <h3>{i.title}</h3>
      <p className="ic-hook">{i.hook}</p>
      <ul>{i.how.map((h) => <li key={h}><Icon name="Check" size={14} /> {h}</li>)}</ul>
      <p className="ic-gain"><Icon name="TrendingUp" size={14} /> {i.gain}</p>
      {i.pitch && <div className="ic-pitch">
        <button className="btn sm ghost" onClick={() => setOpen(!open)}><Icon name="MessageCircle" size={14} /> {open ? "إخفاء" : "رسالة العرض"}</button>
        {open && <><p>{i.pitch}</p><button className="btn sm brand" onClick={() => void copy()}><Icon name="Copy" size={14} /> انسخها</button></>}
      </div>}
    </article>
  );
}

